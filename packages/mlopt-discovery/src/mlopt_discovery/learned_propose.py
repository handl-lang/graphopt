#: Weight of the identity feature — every featurized candidate carries it.
_BIAS = "bias"

_ENUM_NAME = re.compile(r"^enumerate:(?P<fam>[^:]+):\d+$")


# ---------------------------------------------------------------------------
#  Featurization — the pattern-shape view the ranker sees
# ---------------------------------------------------------------------------


def term_stats(term: Any) -> dict[str, float]:
    """Structural statistics of one pattern term.

    Walks the ``Op`` tree once.  Bare ``str`` leaves are metavariables;
    attr *values* that are strings are attr metavariables; ``Const``
    leaves are literal.  Counts are ``log1p``-scaled so one learning
    rate serves every column.
    """
    nodes = 0
    leaves = 0
    mvars: dict[str, int] = {}
    attr_mvars = 0
    consts = 0
    ops: set[str] = set()
    max_arity = 0
    depth = 0

    def walk(t: Any, d: int) -> None:
        nonlocal nodes, leaves, attr_mvars, consts, max_arity, depth
        depth = max(depth, d)
        if isinstance(t, Op):
            nodes += 1
            ops.add(t.op)
            max_arity = max(max_arity, len(t.args))
            for v in t.attrs.values():
                if isinstance(v, str):
                    attr_mvars += 1
            for a in t.args:
                walk(a, d + 1)
        elif isinstance(t, Const):
            consts += 1
            leaves += 1
        elif isinstance(t, str):
            mvars[t] = mvars.get(t, 0) + 1
            leaves += 1
        else:  # Var / Param — a concrete leaf
            leaves += 1

    walk(term, 1)
    return {
        "nodes": float(nodes),
        "depth": float(depth),
        "leaves": float(leaves),
        "mvars": float(len(mvars)),
        "shared_mvars": float(sum(1 for n in mvars.values() if n > 1)),
        "attr_mvars": float(attr_mvars),
        "consts": float(consts),
        "distinct_ops": float(len(ops)),
        "max_arity": float(max_arity),
    }


def _op_hist(term: Any, into: dict[str, float]) -> None:
    """Accumulate ``op:<name>`` counts over *term* into *into*."""
    if isinstance(term, Op):
        into[f"op:{term.op}"] = into.get(f"op:{term.op}", 0.0) + 1.0
        for a in term.args:
            _op_hist(a, into)


def _mvar_set(term: Any, into: set[str]) -> set[str]:
    """Collect the metavariable (bare-str leaf) names of *term*."""
    if isinstance(term, Op):
        for a in term.args:
            _mvar_set(a, into)
    elif isinstance(term, str):
        into.add(term)
    return into


def _enum_family(name: str) -> str | None:
    """Parse the grammar family out of an ``enumerate:<fam>:<n>`` name."""
    m = _ENUM_NAME.match(name)
    return m.group("fam") if m else None


def featurize(
    lhs: Any,
    rhs: Any,
    *,
    family: str = "",
    name: str = "",
    cond: Any = None,
    dspec: Any = None,
) -> dict[str, float]:
    """Return the feature map the ranker scores.

    Three blocks, all ``str -> float`` (the gamekit featurizer idiom —
    a weight table is a same-shaped dict):

    * ``fam:<family>`` / ``enum:<grammar-family>`` one-hots — the
      proposer-family identity the ledger shows is the dominant signal;
    * ``lhs:*`` / ``rhs:*`` / ``pair:*`` — the structural statistics of
      both pattern sides (sizes are ``log1p``-scaled);
    * ``op:<name>`` counts and ``top:<lhs-root-op>`` — the op
      vocabulary the pattern actually uses, so a mutant of
      ``sdpa_fold`` scores differently from an invented shape.
    """
    lft = term_stats(lhs)
    rgt = term_stats(rhs)
    lmvars = _mvar_set(lhs, set())
    rmvars = _mvar_set(rhs, set())
    feats: dict[str, float] = {_BIAS: 1.0}
    for side, s in (("lhs", lft), ("rhs", rgt)):
        for k, v in s.items():
            feats[f"{side}:{k}"] = math.log1p(v)
    feats["pair:rhs_shrinks"] = float(rgt["nodes"] < lft["nodes"])
    feats["pair:rhs_is_leaf"] = float(
        isinstance(rhs, str) or rgt["nodes"] == 0.0
    )
    feats["pair:same_root"] = float(
        isinstance(lhs, Op) and isinstance(rhs, Op) and lhs.op == rhs.op
    )
    feats["pair:alpha_eq"] = float(
        lp._key(lhs, rhs)[0] == lp._key(lhs, rhs)[1]
    )
    feats["pair:new_rhs_mvars"] = float(len(rmvars - lmvars))
    feats["pair:shared_mvar_frac"] = (
        len(rmvars & lmvars) / len(rmvars) if rmvars else 0.0
    )
    feats["meta:has_cond"] = float(cond is not None)
    feats["meta:has_dspec"] = float(dspec is not None)
    if family:
        feats[f"fam:{family}"] = 1.0
    fam = _enum_family(name)
    if fam is not None:
        feats[f"enum:{fam}"] = 1.0
    if isinstance(lhs, Op):
        feats[f"top:{lhs.op}"] = 1.0
    hist: dict[str, float] = {}
    _op_hist(lhs, hist)
    _op_hist(rhs, hist)
    for k, v in hist.items():
        feats[k] = math.log1p(v)
    return feats


def _featurize_proposal(p: Proposal) -> dict[str, float]:
    """Return the proposal view of :func:`featurize`."""
    return featurize(
        p.lhs,
        p.rhs,
        family=p.family,
        name=p.name,
        cond=p.cond,
        dspec=p.dspec,
    )


