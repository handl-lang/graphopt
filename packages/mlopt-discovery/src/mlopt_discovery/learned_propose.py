"""Learned mint proposer — rank and mutate candidates by measured viability.

The enumeration-side proposers (:func:`mlopt_discovery.pipeline.propose`,
``enumerate_candidates``) generate by construction: every grammar form,
every census tuple, every fusion schema gets a slot and the oracle sorts
them out afterwards.  The overnight ledgers
(``bench/results/checkpoints/overnight_*.jsonl``) now carry hundreds of
measured cells — candidate pattern → oracle/pay/cert verdict → novelty
class — which is a *labeled* dataset of which proposal shapes survive.
This module is the learned half of the mint: a small logistic ranker
trained on those cells, plus a mutation generator that proposes
*variants of laws that already earned admission* — op substitutions,
argument swaps, metavariable rewiring and unary wraps — rather than
enumerating a fixed grammar.

Honesty contract
----------------

A learned proposal is a *prior*, never a verdict.  Everything
:func:`propose_learned` emits enters the same pool as the enumeration
mint: it still binds against the corpus (``require_bind``), still gets
deduplicated against the shipped bank by alpha-key, and still faces the
full referee gauntlet + novelty sieve.  The model only decides *which
candidates are worth an episode slot* — the ledger's own rows show why
that matters: the enumeration mint's oracle-pass rate is ~13% overall,
but the rate differs by two orders of magnitude across proposer
families (``synth-composite`` ~90%, ``census-mixed-view`` 0%).  A ranker
that reorders the pool by predicted viability buys back episode slots;
a generator whose mutations start from measured-good laws mints
candidates the fixed grammar cannot spell at all.

Integration seam
----------------

The overnight driver does not call this module yet — the seam it wires
is::

    from mlopt_discovery import learned_propose

    # generation: mutate the known-good bank, bind to the module's term
    extra = learned_propose.propose_learned(
        terms, census_op=dict(counts), top_k=page // 4
    )
    pool.extend(extra)  # Proposal objects, like pipeline.propose emits

    # rerank: reorder an existing pool by predicted viability
    pool = learned_propose.rerank(pool)

    # eval-ordering: feed the game layer's value-injection seam
    open_game.set_value_preds(learned_propose.value_fn())

The weight table (:data:`DEFAULT_WEIGHTS`) is a baked artifact
regenerated by ``scripts/train_learned_proposer.py`` — same convention
as the ``lawdata`` player priors, kept inside this module so the bake
travels with the only consumer.

Pure stdlib + ``mlopt_core`` — no torch, no bench imports — so the
shipped proposer runs anywhere the discovery package does.
"""

