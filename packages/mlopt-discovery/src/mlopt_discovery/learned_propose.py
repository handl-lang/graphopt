def oracle_passed(stages: Any) -> bool:
    """Whether a ledger ``stages`` list cleared the oracle leg.

    The gauntlet runs its components in order and stops at the first
    refusal, so the claim survived the oracle iff the recorded stage
    list either cleared stage ``oracle`` or never ran it (an arm whose
    referee starts downstream) — an empty list is *not* a pass.
    """
    if not stages:
        return False
    for s in stages:
        if s.get("name") == "oracle":
            return bool(s.get("passed"))
    return True


@dataclass(frozen=True)
class LabeledRow:
    """One ledger candidate cell, featurized and labeled.

    ``y`` is the headline label — *survived the oracle leg* — the
    "worth an episode slot" bit the ranker trains on.  ``verdict`` /
    ``relation`` / ``admitted`` are the finer verdicts kept for the
    report: a row can pass the oracle and still die at pay or
    novelty, and those rows are what the precision curve shows.
    """

    name: str
    family: str
    sources: tuple[str, ...]
    features: dict[str, float]
    y: bool
    admitted: bool
    verdict: str
    relation: str
    num_true: Any
    ledger: str
    episode: int
    rule: Rewrite | None = field(default=None, compare=False)


def _rebuild_rule(law: dict[str, Any]) -> Rewrite | None:
    """Best-effort ``Rewrite`` rebuild of a serialized law (None on miss)."""
    from mlopt_core.laws.serialize import object_from_data

    try:
        obj = object_from_data(law)
    except Exception:
        return None
    return obj if isinstance(obj, Rewrite) else None


def _row_from_cell(
    cell: Mapping[str, Any], ledger: str, with_rules: bool
) -> LabeledRow | None:
    """Convert one ledger ``candidate`` record to a :class:`LabeledRow`.

    ``None`` when the serialized law fails to deserialize — a
    partially-written ledger tail is a truncated record, not an error.
    """
    law = cell.get("law") or {}
    try:
        lhs = term_from_data(law["lhs"])
        rhs = term_from_data(law["rhs"])
    except Exception:
        return None
    arena = cell.get("arena") or {}
    return LabeledRow(
        name=cell.get("name", ""),
        family=cell.get("family") or "enumerate",
        sources=tuple(cell.get("sources") or ()),
        features=featurize(
            lhs,
            rhs,
            family=cell.get("family") or "",
            name=cell.get("name", ""),
            cond=law.get("cond"),
            dspec=law.get("dspec"),
        ),
        y=oracle_passed(cell.get("stages")),
        admitted=bool(cell.get("admitted")),
        verdict=str(arena.get("verdict", "")),
        relation=str(arena.get("relation", "")),
        num_true=arena.get("num_true"),
        ledger=ledger,
        episode=int(cell.get("episode", 0)),
        rule=_rebuild_rule(law) if with_rules else None,
    )


def load_ledger_rows(
    paths: Iterable[str | Path],
    *,
    with_rules: bool = False,
) -> list[LabeledRow]:
    """Read candidate cells out of overnight ledger JSONL files.

    Every ``("candidate", name)`` record becomes one :class:`LabeledRow`
    — the serialized law is featurized directly (``term_from_data`` on
    the ``lhs``/``rhs`` fields, no ``Rewrite`` rebuild needed).  Rows
    whose law fails to deserialize are skipped rather than fatal — a
    partially-written ledger tail is a truncated record, not an error.
    ``with_rules`` additionally rebuilds the fireable ``Rewrite`` (for
    callers that want the labeled laws themselves — e.g. extra
    mutation seeds); rows with procedural-hook laws
    (``missing_hooks``) rebuild bare-pattern rules, which is the same
    shape the mint already mints them as.
    """
    rows: list[LabeledRow] = []
    for path in paths:
        p = Path(path)
        if not p.is_file():
            continue
        for line in p.read_text().splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            if rec.get("key", [None])[0] != "candidate":
                continue
            row = _row_from_cell(rec["record"], p.name, with_rules)
            if row is not None:
                rows.append(row)
    return rows


def expand_ledgers(
    globs: Iterable[str] = LEDGER_GLOBS,
    *,
    root: str | Path | None = None,
) -> list[Path]:
    """Resolve the ledger glob list to existing paths (sorted)."""
    base = Path(root) if root is not None else Path.cwd()
    out: list[Path] = []
    for g in globs:
        if any(ch in g for ch in "*?["):
            out.extend(base.glob(g))
        else:
            p = Path(g)
            out.append(p if p.is_absolute() else base / p)
    return sorted({p.resolve() for p in out if p.is_file()})


# ---------------------------------------------------------------------------
#  The model — a logistic ranker over feature dicts
# ---------------------------------------------------------------------------


def _dot(
    weights: Mapping[str, float], feats: Mapping[str, float]
) -> float:
    """Sparse dot product — the gamekit ``_dot`` idiom."""
    return sum(weights.get(f, 0.0) * v for f, v in feats.items())


def _sigmoid(z: float) -> float:
    """Numerically-tame logistic."""
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


@dataclass(frozen=True)
class ProposerModel:
    """A baked logistic ranker: ``weights`` over :func:`featurize` keys.

    ``score`` returns P(candidate survives the oracle leg) — the
    reranker sorts on it, the generator prunes on it, and
    :func:`value_fn` exposes it to the open game's value-injection
    seam.  ``predict`` takes any ``(lhs, rhs, family, name)`` shape.
    """

    weights: Mapping[str, float] = field(default_factory=dict)

    def score_features(self, feats: Mapping[str, float]) -> float:
        """P(oracle-pass) for a featurized candidate."""
        return _sigmoid(_dot(self.weights, feats))

    def score(self, lhs: Any, rhs: Any, **kw: Any) -> float:
        """P(oracle-pass) for a raw pattern pair."""
        return self.score_features(featurize(lhs, rhs, **kw))

    def predict_proposal(self, p: Proposal) -> float:
        """P(oracle-pass) for a pipeline ``Proposal``."""
        return self.score_features(_featurize_proposal(p))

    def predict_candidate(self, cand: Any) -> float:
        """P(oracle-pass) for a ``proposal.Candidate`` (game-layer row)."""
        return self.score(
            cand.lhs, cand.rhs, family="", name=cand.label
        )


def average_precision(rows: Iterable[tuple[float, bool]]) -> float:
    """AP of a ``(score, label)`` stream — the ranking-quality measure."""
    pairs = sorted(rows, key=lambda t: -t[0])
    total = sum(1 for _s, y in pairs if y)
    if total == 0:
        return 0.0
    hits = 0
    ap = 0.0
    for i, (_s, y) in enumerate(pairs, start=1):
        if y:
            hits += 1
            ap += hits / i
    return ap / total


def precision_at(rows: Iterable[tuple[float, bool]], k: int) -> float:
    """Precision of the top-*k* scores in a ``(score, label)`` stream."""
    top = sorted(rows, key=lambda t: -t[0])[: max(k, 0)]
    if not top:
        return 0.0
    return sum(1 for _s, y in top if y) / len(top)


def train(
    rows: Iterable[LabeledRow],
    *,
    epochs: int = 300,
    lr: float = 0.3,
    l2: float = 1e-3,
    seed: int = 0,
) -> ProposerModel:
    """Fit the logistic ranker on labeled rows — plain SGD, no torch.

    The dataset is a few hundred rows of ~60-dim sparse features:
    full-batch would be overkill machinery and a per-epoch shuffled
    pass converges in seconds.  ``l2`` shrinks the family one-hots
    toward the structural features so an unseen proposer family still
    scores off its shape rather than a memorized prior.
    """
    rows = list(rows)
    weights: dict[str, float] = {}
    rng = random.Random(seed)
    for _ in range(epochs):
        rng.shuffle(rows)
        for row in rows:
            feats = row.features
            err = _sigmoid(_dot(weights, feats)) - (
                1.0 if row.y else 0.0
            )
            for f, v in feats.items():
                weights[f] = (
                    weights.get(f, 0.0) * (1.0 - lr * l2) - lr * err * v
                )
    return ProposerModel(weights=weights)


def evaluate(
    model: ProposerModel, rows: Iterable[LabeledRow]
) -> dict[str, float]:
    """AP / precision@10 / base rate of *model* on *rows*."""
    rows = list(rows)
    scored = [(model.score_features(r.features), r.y) for r in rows]
    base = sum(1 for _s, y in scored if y) / max(len(scored), 1)
    return {
        "n": float(len(scored)),
        "base_rate": base,
        "ap": average_precision(scored),
        "ap_base": base,
        "p@10": precision_at(scored, 10),
        "p@25": precision_at(scored, 25),
    }


# ---------------------------------------------------------------------------
#  Mutation — candidates the grammar cannot spell
# ---------------------------------------------------------------------------


def _op_sites(
    term: Any, path: tuple = ()
) -> Iterator[tuple[tuple, Op]]:
    """Yield ``(path, Op)`` for every op node of *term*, pre-order."""
    if isinstance(term, Op):
        yield path, term
        for i, a in enumerate(term.args):
            yield from _op_sites(a, (*path, i))


def _rebuild(term: Any, path: tuple, new: Any) -> Any:
    """Return *term* with the node at *path* replaced by *new*."""
    if not path:
        return new
    node = cast(Op, term)
    args = list(node.args)
    args[path[0]] = _rebuild(args[path[0]], path[1:], new)
    return Op.make(node.op, *args, **dict(node.attrs))


def _leaf_paths(
    term: Any, path: tuple = ()
) -> Iterator[tuple[tuple, Any]]:
    """Yield ``(path, leaf)`` for every non-Op leaf of *term*."""
    if isinstance(term, Op):
        for i, a in enumerate(term.args):
            yield from _leaf_paths(a, (*path, i))
    else:
        yield path, term


def _try_op(
    op: str, args: tuple, attrs: Mapping[str, Any]
) -> Op | None:
    """``Op.make`` under mutation — invalid attr spellings mint nothing."""
    try:
        return Op.make(op, *args, **dict(attrs))
    except Exception:
        return None


def _arity_ok(op: str, n_args: int) -> bool:
    """``OpMeta.arity`` gate — ``None`` (variadic) substitutes anywhere."""
    meta = REGISTRY.get(op)
    return meta is None or meta.arity in (None, n_args)


def _op_subs(
    rule: Rewrite, ops: Iterable[str]
) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``op-sub`` pre-dedup mutants of *rule*'s lhs."""
    lhs, rhs = rule.lhs, rule.rhs
    for path, node in _op_sites(lhs):
        for new_op in ops:
            if new_op == node.op or not _arity_ok(
                new_op, len(node.args)
            ):
                continue
            new_node = _try_op(new_op, node.args, node.attrs)
            if new_node is None:
                continue
            yield (
                "op-sub",
                f"{node.op}>{new_op}@{'/'.join(map(str, path)) or '/'}",
                _rebuild(lhs, path, new_node),
                rhs,
            )


def _arg_swaps(rule: Rewrite) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``arg-swap`` pre-dedup mutants — binary operands exchanged."""
    lhs, rhs = rule.lhs, rule.rhs
    for path, node in _op_sites(lhs):
        if len(node.args) != 2:
            continue
        a, b = node.args
        new_node = _try_op(node.op, (b, a), node.attrs)
        if new_node is None:
            continue
        yield (
            "arg-swap",
            f"@{'/'.join(map(str, path)) or '/'}",
            _rebuild(lhs, path, new_node),
            rhs,
        )


def _mvar_rewires(rule: Rewrite) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``mvar-rewire`` mutants — rebind one rhs metavariable."""
    lhs, rhs = rule.lhs, rule.rhs
    lmvars = _mvar_set(lhs, set())
    for old in sorted(_mvar_set(rhs, set())):
        for new in sorted(lmvars - {old}):
            rebuilt = rhs
            for path, leaf in _leaf_paths(rhs):
                if leaf == old:
                    rebuilt = _rebuild(rebuilt, path, new)
            yield ("mvar-rewire", f"{old}>{new}", lhs, rebuilt)


def _wraps(
    rule: Rewrite, unary: Iterable[str]
) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``wrap`` pre-dedup mutants — one lhs metavar wrapped."""
    lhs, rhs = rule.lhs, rule.rhs
    for path, leaf in _leaf_paths(lhs):
        if not isinstance(leaf, str):
            continue
        for u in unary:
            new_node = _try_op(u, (leaf,), {})
            if new_node is None:
                continue
            yield (
                "wrap",
                f"{u}@{'/'.join(map(str, path))}",
                _rebuild(lhs, path, new_node),
                rhs,
            )


def _attr_drops(rule: Rewrite) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``attr-drop`` pre-dedup mutants — one attr key removed."""
    lhs, rhs = rule.lhs, rule.rhs
    for path, node in _op_sites(lhs):
        for key in node.attrs:
            attrs = {k: v for k, v in node.attrs.items() if k != key}
            new_node = _try_op(node.op, node.args, attrs)
            if new_node is None:
                continue
            yield (
                "attr-drop",
                f"{key}@{'/'.join(map(str, path)) or '/'}",
                _rebuild(lhs, path, new_node),
                rhs,
            )


def mutations(
    rule: Rewrite,
    *,
    ops: Iterable[str] = (),
    unary: Iterable[str] = (),
    kinds: Iterable[str] = MUTATION_KINDS,
) -> Iterator[tuple[str, str, Any, Any]]:
    """Yield ``(kind, tag, lhs, rhs)`` mutants of *rule*'s pattern pair.

    Five operators, each applied at every applicable site of the
    rule's ``lhs`` (``rhs`` stays the seed's, except where the
    mutation rewires it — the claim a mutant makes is deliberately a
    near-neighbour of a law that already measured true):

    * ``op-sub`` — one ``Op`` node re-spelled as another op of the
      same arity, drawn from *ops* (the corpus/shipped vocabulary);
      attr spellings the new op cannot validate are skipped;
    * ``arg-swap`` — a binary node's operands exchanged;
    * ``mvar-rewire`` — every ``rhs`` occurrence of one metavariable
      rebound to a *different* lhs metavariable (the claim now
      equates two operands the seed kept distinct — the family the
      ``cancel-self`` grammar forms live in);
    * ``wrap`` — one metavariable leaf of ``lhs`` wrapped in a unary
      op from *unary* (deepens the pattern — the ``factor``/
      ``unary-absorb`` direction);
    * ``attr-drop`` — one attribute key removed from one ``Op`` node
      (the ``rekey`` family — relaxes an attr precondition).

    Mutations never touch a seed's guard: a mutant emits as a bare
    pattern pair (``cond``/``dspec``/hooks are the seed's own
    account), which is also what keeps the alpha-key dedup honest.
    """
    generators = {
        "op-sub": lambda: _op_subs(rule, ops),
        "arg-swap": lambda: _arg_swaps(rule),
        "mvar-rewire": lambda: _mvar_rewires(rule),
        "wrap": lambda: _wraps(rule, unary),
        "attr-drop": lambda: _attr_drops(rule),
    }
    seen: set = {lp._key(rule.lhs, rule.rhs)}
    for kind in kinds:
        gen = generators.get(kind)
        if gen is None:
            continue
        for cand in gen():
            key = lp._key(cand[2], cand[3])
            if key in seen:
                continue
            seen.add(key)
            yield cand


def _subterm_ops(terms: Iterable[Any]) -> set[str]:
    """Every op name occurring in the corpus terms."""
    out: set[str] = set()
    for t in terms:
        for _path, node in _op_sites(t):
            out.add(node.op)
    return out


def _binds_any(lhs: Any, terms: Iterable[Any]) -> bool:
    """``_term_match`` against every ``Op`` subterm of *terms*."""
    for t in terms:
        for _path, node in _op_sites(t):
            if _term_match(lhs, node) is not None:
                return True
    return False


def _seed_bank(seeds: Iterable[Any] | None) -> list[Rewrite]:
    """Return the mutation seed set — default: the machine-shipped laws."""
    if seeds is not None:
        return [
            s if isinstance(s, Rewrite) else s.as_rule() for s in seeds
        ]
    return [r for r in ALL_RULES if r.name in MACHINE_SHIPPED]


def _default_ops(
    terms: Iterable[Any], seed_rules: list[Rewrite]
) -> tuple[str, ...]:
    """Return the op-substitution alphabet: corpus + seed + pointwise ops."""
    from mlopt_core.opmeta import POINTWISE_BINARY_OPS

    out = _subterm_ops(terms)
    for r in seed_rules:
        out |= _subterm_ops((r.lhs, r.rhs))
    out |= set(POINTWISE_BINARY_OPS)
    return tuple(sorted(out))


def _default_unary(terms: Iterable[Any]) -> tuple[str, ...]:
    """Return the wrap alphabet: corpus unary ops + shipped unary ops."""
    from mlopt_discovery.lawdata import GRAMMAR_UNARY_OPS

    arity1 = {
        node.op
        for t in terms
        for _p, node in _op_sites(t)
        if len(node.args) == 1
    }
    return tuple(sorted(set(GRAMMAR_UNARY_OPS) | arity1))


def propose_learned(
    terms: Iterable[Any],
    *,
    seeds: Iterable[Any] | None = None,
    model: ProposerModel | None = None,
    ops: Iterable[str] | None = None,
    unary: Iterable[str] | None = None,
    top_k: int | None = None,
    seed: int = 0,
    require_bind: bool = True,
    bank: Iterable[Rewrite] | None = None,
    kinds: Iterable[str] = MUTATION_KINDS,
    census_op: Any = None,
) -> list[Proposal]:
    """Mint learned candidates over the corpus *terms*.

    The overnight seam (its ``_RealArena`` twin): seeds default to the
    machine-shipped bank, every seed's :func:`mutations` stream is
    minted, alpha-deduplicated against itself *and* the shipped law
    bank (a mutant that re-spells a shipped law is ``known-art``
    waiting to happen — the sieve would refuse it anyway, so do not
    spend an episode slot on it), filtered to patterns whose LHS
    binds a real subterm (``require_bind``, the corpus-mint
    contract), ranked by the learned model, and returned as
    ``family="learned-mint"`` ``Proposal``s — the same element type
    :func:`mlopt_discovery.pipeline.propose` emits, so the caller
    appends, wraps in ``Candidate``s, and the gauntlet does the rest.

    *census_op* is accepted (and ignored) for signature symmetry with
    ``pipeline.propose`` — a call site that already has the census in
    hand can pass it without a second argument shape.

    ``top_k`` bounds the returned slice *after* ranking — ``None``
    returns the whole surviving mint, ranked.
    """
    terms = list(terms)
    model = DEFAULT_MODEL if model is None else model
    seed_rules = _seed_bank(seeds)
    op_vocab = (
        tuple(sorted(ops))
        if ops is not None
        else _default_ops(terms, seed_rules)
    )
    unary_vocab = (
        tuple(sorted(unary))
        if unary is not None
        else _default_unary(terms)
    )
    shipped = {
        lp._key(r.lhs, r.rhs)
        for r in (ALL_RULES if bank is None else bank)
    }
    scored = _scored_mutants(
        seed_rules,
        terms,
        model=model,
        op_vocab=op_vocab,
        unary_vocab=unary_vocab,
        kinds=kinds,
        shipped=shipped,
        require_bind=require_bind,
        rng=random.Random(seed),
    )
    scored.sort(key=lambda t: -t[0])
    out = [p for _s, p in scored]
    return out[:top_k] if top_k is not None else out


def _scored_mutants(
    seed_rules: list[Rewrite],
    terms: list[Any],
    *,
    model: ProposerModel,
    op_vocab: tuple[str, ...],
    unary_vocab: tuple[str, ...],
    kinds: Iterable[str],
    shipped: set,
    require_bind: bool,
    rng: random.Random,
) -> list[tuple[float, Proposal]]:
    """Mint, dedup, bind-filter and score every seed's mutant stream.

    The dedup key set starts at the shipped bank's alpha keys — a
    mutant that re-spells a shipped law is ``known-art`` waiting to
    happen, so the mint never spends an episode slot on it — and
    grows as mutants mint, so a shape reachable from two seeds mints
    once (first seed in bank order, after *rng*'s per-seed shuffle).
    """
    seed_keys = {lp._key(r.lhs, r.rhs) for r in seed_rules}
    seen: set = set(shipped)
    scored: list[tuple[float, Proposal]] = []
    for rule in seed_rules:
        muts = [
            m
            for m in mutations(
                rule, ops=op_vocab, unary=unary_vocab, kinds=kinds
            )
            if lp._key(m[2], m[3]) not in seed_keys
        ]
        rng.shuffle(muts)
        for kind, tag, lhs, rhs in muts:
            key = lp._key(lhs, rhs)
            if key in seen or (
                require_bind and not _binds_any(lhs, terms)
            ):
                continue
            seen.add(key)
            p = Proposal(
                name=f"learned:{rule.name}:{kind}:{tag}",
                lhs=lhs,
                rhs=rhs,
                family="learned-mint",
                sources=("learned-mint", rule.name, kind),
            )
            scored.append((model.predict_proposal(p), p))
    return scored


def rerank(
    proposals: Iterable[Proposal],
    *,
    model: ProposerModel | None = None,
    blend: float = 0.0,
) -> list[Proposal]:
    """Sort *proposals* by predicted oracle-pass viability, descending.

    ``blend`` mixes the model score with the pool order
    (``blend * index_fraction``) — a value in ``(0, 1]`` keeps a tail
    of low-scored candidates ahead of pure truncation, the
    exploration half of a learned proposer that still wants
    calibration data from the bottom of its own ranking.
    """
    model = DEFAULT_MODEL if model is None else model
    props = list(proposals)
    n = max(len(props) - 1, 1)
    keyed = [
        (model.predict_proposal(p) + blend * (i / n), i, p)
        for i, p in enumerate(props)
    ]
    keyed.sort(key=lambda t: (-t[0], t[1]))
    return [p for _s, _i, p in keyed]


def value_fn(model: ProposerModel | None = None) -> Any:
    """Return a ``cand -> float`` callable for ``open_game.set_value_preds``.

    Feeds the open game's ``open:next-val`` feature part — the
    injection seam ``stop_policy``'s torch ``RuleValueNet`` used,
    backed here by the torch-free ledger ranker.  Scores are the
    model's P(oracle-pass); the feature part rescales.
    """
    model = DEFAULT_MODEL if model is None else model
    return model.predict_candidate


