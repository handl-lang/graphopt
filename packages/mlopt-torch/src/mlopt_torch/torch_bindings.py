def _expand_torch(t: Any, *a: Any, **kw: Any) -> Any:
    """``t.expand`` binding: the target shape arrives as attrs or args.

    ``shape`` / ``dim`` attrs or positional args — a size sequence OR a
    bare int.  Splat sequences; pass a scalar through (``t.expand(*4)``
    would be a ``TypeError``, ``t.expand(4)``/``t.expand(-1)`` is
    legal).
    """
    dim_v = kw.get("shape") or kw.get("dim") or a
    if isinstance(dim_v, (tuple, list)):
        return t.expand(*dim_v)
    return t.expand(dim_v)


def _scalar_value(v: Any) -> Any:
    """Unwrap a Const-evaluated scalar to a Python number.

    A Const-evaluated scalar arrives as a 0-dim tensor — unwrap it
    to the Python number the aten call expects.
    """
    if torch.is_tensor(v):
        return v.item() if v.dim() == 0 else v
    return v


def _pack_torch(*ts: Any) -> tuple:
    """``pack`` — pair the model's output wires into one tuple.

    The multi-output root's binding: the operands are already
    evaluated, so packing is pure wire bookkeeping (no kernel) — it
    returns the tuple the original module's ``forward`` returned, one
    entry per output in export order.
    """
    return tuple(ts)


def _to_torch(x: Any, *a: Any, **kw: Any) -> Any:
    """``to`` — apply the recorded dtype AND device casts.

    ``aten.to.dtype``/``.dtype_layout``/``.device`` all canonicalise
    to ``to``; the boundary records ``dtype`` (short name) and
    ``device`` (canonical string) as attrs.  Either may be absent —
    ``x.to(y)`` exports both positionally.  With neither, the term
    is the identity cast the no-attr spelling always was.
    """
    dtype = _creator_dtype(kw)
    device = _creator_device(kw)
    if dtype is None and device is None:
        return x
    cast_kw: dict[str, Any] = {}
    if dtype is not None:
        cast_kw["dtype"] = dtype
    if device is not None:
        cast_kw["device"] = device
    return x.to(**cast_kw)


def _scatter_torch(t: Any, idx: Any, v: Any = None, **kw: Any) -> Any:
    """``scatter`` covers both aten spellings.

    ``scatter.src`` (src operand) and ``scatter.value`` (Const
    operand that evals to a 0-dim tensor — unwrap it to the Number
    the value overload wants).
    """
    dim = int(attr_of(kw, "dim", default=0))
    if torch.is_tensor(v) and v.dim() == 0:
        v = v.item()
    if torch.is_tensor(v):
        return t.scatter(dim, idx, v)
    return t.scatter(dim, idx, value=v)


def _index_torch(t: Any, *idxs: Any, **kw: Any) -> Any:
    """``index`` — numpy-style advanced indexing.

    ``layout`` marks the key positions that carry an index operand
    (True) vs a full slice (False); minted terms without it index
    the leading axes.
    """
    layout = attr_of(kw, "layout", default=None) or (True,) * len(idxs)
    it = iter(idxs)
    key = tuple(
        next(it) if is_idx else slice(None) for is_idx in layout
    )
    return t[key]


def _index_put_torch(t: Any, *a: Any, **kw: Any) -> Any:
    """``index_put`` — the functional ``x[key] = v``.

    The index operands come first (counted by ``layout``'s True
    entries), the values operand last; ``accumulate`` is an attr.
    """
    layout = attr_of(kw, "layout", default=None) or ()
    n_idx = sum(1 for flag in layout if flag)
    if layout:
        it = iter(a[:n_idx])
        key = tuple(
            next(it) if is_idx else slice(None) for is_idx in layout
        )
        value = a[n_idx] if len(a) > n_idx else None
    else:
        # Minted term without layout: all-but-last operands index
        # leading axes, the last is the value.
        key = tuple(a[:-1])
        value = a[-1] if a else None
    acc = bool(attr_of(kw, "accumulate", default=False))
    return torch.index_put(
        t, cast(Any, key), cast(Any, value), accumulate=acc
    )


def _arange_torch(*a: Any, **kw: Any) -> Any:
    """``arange`` — the bounds arrive as Const operands.

    ``arange`` is in ``_SCALAR_OPERAND_OPS``; operands are
    evaluated to 0-dim tensors.
    """
    vals = [_scalar_value(v) for v in a]
    if not vals:
        vals = [
            _scalar_value(kw[k])
            for k in sorted(
                (k for k in kw if is_positional_attr(k)),
                key=lambda k: int(k[3:]),
            )
        ]
    return torch.arange(
        *vals, dtype=_creator_dtype(kw), device=_creator_device(kw)
    )


def _where_torch(c: Any, *a: Any, **kw: Any) -> Any:
    """``where(cond, x, y)`` — self/other may be attr-carried.

    aten.where's operand positions (1=self, 2=other) each arrive
    either as a child operand — in order, after the cond — or as an
    ``argN`` attr: scalar spellings minted before ``where`` joined
    ``_SCALAR_OPERAND_OPS`` (``where(c, x, arg2=-inf)`` — the decoder
    mask) or hand-minted terms.  ``arg1``/``arg2`` claim their
    position; the remaining children fill the unclaimed slots in
    order, so ``where(c, arg1=-1, y)`` (ScalarSelf) and
    ``where(c, x, arg2=-inf)`` (ScalarOther) both rebuild exactly.
    """
    slots = [attr_of(kw, "arg1"), attr_of(kw, "arg2")]
    it = iter(a)
    filled = [s if s is not None else next(it, None) for s in slots]
    x, y = filled
    if x is None or y is None:
        raise TypeError(
            "where requires self/other operands — children or "
            "arg1/arg2 attrs, got neither"
        )
    _sentinel = object()
    if next(it, _sentinel) is not _sentinel:
        # A third child beyond the two operand slots has no aten
        # meaning — dropping it silently would compute where/2.
        raise TypeError(
            "where takes exactly two value operands (self/other) — "
            f"got surplus children {a}"
        )
    return torch.where(c, x, y)


def _batch_norm_torch(x: Any, *a: Any, **kw: Any) -> Any:
    """``aten.batch_norm`` → F.batch_norm's operand order.

    ``aten.batch_norm(x, w, b, rm, rv, ...)`` →
    F.batch_norm's (x, rm, rv, w, b, ...) operand order.  None
    weight/bias are dropped at export, so the affine pair is
    whatever sits between x and the running stats (a lone mid
    operand reads as weight).

    ``track_running_stats=False`` exports ``running_mean``/
    ``running_var`` as ``None`` — dropped at export, leaving only
    the affine operands.  Export tags that spelling
    ``running_stats=False`` because len-2 is genuinely ambiguous
    (``(w, b)`` vs ``(rm, rv)``) and arity alone cannot decide;
    without the tag (a hand-minted term) the legacy last-two
    heuristic applies.
    """
    if attr_of(kw, "running_stats", default=None) is False:
        # No running stats exist — every operand is affine.  Fewer
        # than three means at most the (w, b) pair survived.
        if len(a) > 2:
            raise TypeError(
                "batch_norm with running_stats=False carries at "
                f"most the affine pair (w, b) — got {len(a)} "
                "operands; the running-stats slots were exported "
                "as None and cannot reappear"
            )
        rm = rv = None
        w = a[0] if len(a) >= 1 else None
        b = a[1] if len(a) >= 2 else None
    else:
        rm, rv = a[-2], a[-1]
        mid = a[:-2]
        w = mid[0] if len(mid) >= 1 else None
        b = mid[1] if len(mid) >= 2 else None
    return torch.nn.functional.batch_norm(
        x,
        rm,
        rv,
        weight=w,
        bias=b,
        training=bool(attr_of(kw, "training", default=False)),
        momentum=float(attr_of(kw, "momentum", default=0.1)),
        eps=float(attr_of(kw, "eps", default=1e-5)),
    )


def _instance_norm_torch(x: Any, *a: Any, **kw: Any) -> Any:
    """``aten.instance_norm`` → F.instance_norm's operand order.

    ``aten.instance_norm(x, w, b, rm, rv, use_input_stats, momentum,
    eps, cudnn)`` — None operands drop at export, so the operand list
    is whatever survived: the affine pair fills the leading slots,
    and the running-stats pair is the tail iff ``use_input_stats`` is
    False (the eval-mode export of a ``track_running_stats=True``
    module).  ``cudnn_enabled`` is a dispatch hint, not semantics —
    F.instance_norm has no such kwarg.
    """
    uis = bool(attr_of(kw, "use_input_stats", default=True))
    stats_ok = not uis and len(a) >= 2
    rm, rv = (a[-2], a[-1]) if stats_ok else (None, None)
    mid = a[:-2] if stats_ok else a
    w = mid[0] if len(mid) >= 1 else None
    b = mid[1] if len(mid) >= 2 else None
    return torch.nn.functional.instance_norm(
        x,
        running_mean=rm,
        running_var=rv,
        weight=w,
        bias=b,
        use_input_stats=uis,
        momentum=float(attr_of(kw, "momentum", default=0.1)),
        eps=float(attr_of(kw, "eps", default=1e-5)),
    )


def _upsample_bilinear2d_torch(x: Any, *a: Any, **kw: Any) -> Any:
    """``aten.upsample_bilinear2d[.vec]`` → F.interpolate bilinear.

    The bilinear twin of :func:`_upsample_nearest2d_torch` — same
    ``size``/``scale`` attr convention, ``align_corners=False`` (the
    default torch.export emits).
    """
    size = a[0] if a else attr_of(kw, "size", default=None)
    align = (
        bool(a[1])
        if len(a) > 1
        else bool(kw.get("align_corners", False))
    )
    scale = a[2] if len(a) > 2 else attr_of(kw, "scale", default=None)
    if isinstance(size, int) and not isinstance(size, bool):
        size = (size, size)
    if isinstance(scale, (int, float)) and not isinstance(scale, bool):
        scale = (float(scale), float(scale))
    return torch.nn.functional.interpolate(
        x,
        size=size,
        scale_factor=scale,
        mode="bilinear",
        align_corners=align,
    )


