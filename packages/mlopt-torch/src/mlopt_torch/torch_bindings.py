class FunctorchReplayError(RuntimeError):
    """An ``opaque`` term named inlined functorch/vmap plumbing.

    ``torch.export`` traces *through* ``torch.vmap`` (dynamo inlines
    the transform — ``torch._dynamo.trace_rules`` marks the
    ``torch._functorch.predispatch`` calls
    ``TorchInGraphFunctionVariable``), so a graph that ran a vmapped
    region lifts to IR carrying ``_add_batch_dim`` /
    ``_remove_batch_dim`` / ``_vmap_*_nesting`` opaque leaves around
    ordinary payload ops.  Replaying those predispatch calls eagerly
    mints ``BatchedTensor``s no active vmap level owns — the next
    pointwise op dies in ``gen_vmap_plumbing`` ("tensor escaped from
    inside a function being vmapped"), e.g. the whisper decoder's
    HF ``masking_utils._vmap_for_bhqkv`` causal-mask construction
    (``docs/reports/realcorpus_mint_r3.md`` F1).  The plumbing can
    never execute outside a vmap, so the binding refuses up front
    with a named error instead of surfacing the cryptic downstream
    crash — callers (the referee pay leg) record the case as
    *unverifiable*, never as a verify disagreement.
    """


#: Qualname module prefixes whose eager replay cannot be faithful —
#: functorch transforms are trace-time machinery, not kernels.
_FUNCTORCH_QUAL_MODULES = ("torch._functorch", "torch._C._functorch")


def _is_functorch_qual(qual: str) -> bool:
    """Return True when *qual* names functorch/vmap plumbing."""
    module = qual.split(":", 1)[0].split("::", 1)[0]
    return module.startswith(_FUNCTORCH_QUAL_MODULES) or (
        module == "torch.func" or module.startswith("torch.func.")
    )


def _opaque_torch(*args: Any, **kw: Any) -> Any:
    """``opaque`` binding — replay the original torch callable.

    ``aten`` is the qualname resolved by :func:`_resolve_opaque_callable`;
    ``sig`` replays ``node.args``/``node.kwargs`` positionally —
    ``("t", i)`` slots consume evaluated operands in mint order.
    """
    qual = kw["aten"]
    if _is_functorch_qual(qual):
        raise FunctorchReplayError(
            f"opaque op {qual!r}: inlined functorch/vmap plumbing "
            "cannot replay eagerly — the export traced through "
            "torch.vmap and the IR carries its predispatch calls; "
            "the module is unverifiable through this sink"
        )
    arg_specs, kw_specs = kw["sig"]
    operands = iter(args)

    def build(s: Any) -> Any:
        kind = s[0]
        if kind == "t":
            return next(operands)
        if kind == "l":
            return s[1]
        if kind == "cx":
            return complex(s[1], s[2])
        if kind == "dev":
            return torch.device(s[1])
        if kind == "lst":
            return [build(x) for x in s[1]]
        if kind == "tpl":
            return tuple(build(x) for x in s[1])
        if kind == "map":
            return {k: build(v) for k, v in s[1]}
        if kind == "dt":
            return _creator_dtype({"dtype": s[1]})
        raise TypeError(
            f"opaque op {qual!r}: unencodable argument spec {s!r}"
        )

    call_args = [build(s) for s in arg_specs]
    call_kwargs = {k: build(v) for k, v in kw_specs}
    return _resolve_opaque(qual)(*call_args, **call_kwargs)


def _extreme_torch(
    elem_fn: Callable[[Any, Any], Any],
    name: str,
    x: Any,
    a: tuple,
    kw: dict,
) -> Any:
    """Bind ``min``/``max``: elementwise on a second operand, else reduce.

    The exporter renames the aten ``other`` overload to
    ``minimum``/``maximum``, so a *positional* second operand reaching
    this binding can only come from a hand-minted term — and the only
    honest reading of ``min(x, y)`` is the elementwise form (the
    reduction's ``dim``/``keepdim`` are attrs, never operands).
    Routing it to ``torch.minimum``/``torch.maximum`` binds correctly;
    the previous unconditional ``torch.min(x)`` silently dropped the
    operand — the t5-small silent-wrong-answer wall.  Extra positionals
    beyond the second operand fail loudly rather than being dropped.
    """
    if a:
        if len(a) != 1 or kw:
            raise ValueError(
                f"op '{name}' got {len(a)} positional operand(s) plus "
                f"attrs {sorted(kw)} — the elementwise two-operand "
                f"spelling is '"
                + ("minimum" if name == "min" else "maximum")
                + "'"
            )
        return elem_fn(x, a[0])
    if attr_of(kw, "dim", "axis", default=None) is None:
        return (torch.min if name == "min" else torch.max)(x)
    return (torch.min if name == "min" else torch.max)(
        x,
        dim=_dim_args(a, kw)[0],
        keepdim=bool(attr_of(kw, "keepdim", default=False)),
    )


def _clamp_torch(t: Any, *a: Any, **kw: Any) -> Any:
    """Bind ``clamp`` — tensor bounds keep their aten slot via ``argpos``.

    ``aten.clamp.Tensor(self, min?, max?)`` elides a ``None`` bound, so
    the surviving tensor args lose their slot identity in the flat arg
    list: without the exporter's ``argpos`` record, ``clamp(a, max=b)``
    minted the same term as ``clamp(a, min=b)`` and silently applied
    the wrong bound (the same silent-wrong-answer class as the
    ``aten.min`` ``other`` wall).  ``argpos`` maps each positional arg
    back to its aten position (1=min, 2=max); scalar bounds still
    arrive under the canonical ``min``/``max`` attrs.
    """
    argpos = kw.pop("argpos", None)
    lo = attr_of(kw, "min", default=None)
    hi = attr_of(kw, "max", default=None)
    if argpos is None:
        # Hand-minted/legacy spelling: positional args fill min then
        # max (attrs win, as before); anything past two operands is
        # meaningless and fails loudly rather than dropping silently.
        if len(a) > 2:
            raise ValueError(
                f"op 'clamp' got {len(a)} positional operands — "
                "at most two (min, max)"
            )
        if a:
            if lo is None:
                lo = a[0]
            if len(a) > 1 and hi is None:
                hi = a[1]
        return torch.clamp(t, min=lo, max=hi)
    if len(a) != len(argpos):
        raise ValueError(
            f"op 'clamp': {len(a)} tensor bound(s) but argpos "
            f"{tuple(argpos)} — the term is malformed"
        )
    for pos, v in zip(argpos, a, strict=True):
        if pos == 1:
            lo = v
        elif pos == 2:
            hi = v
        else:
            raise ValueError(
                f"op 'clamp': tensor bound at unexpected aten "
                f"position {pos} (expected 1=min or 2=max)"
            )
    return torch.clamp(t, min=lo, max=hi)


# ---------------------------------------------------------------------------
#  sdpa backend policy
# ---------------------------------------------------------------------------
# ``F.scaled_dot_product_attention`` lets PyTorch pick the first enabled
# backend it supports.  With fp32 + ``attn_mask`` the flash and cuDNN
# backends are unavailable, so EVERY attention lands on the mem-efficient
# fmha cutlass kernel — which microbenchmarks ~2.4-4.7x SLOWER than the
# math backend at decode shapes (short query axis, long key axis: the
# fmha tile setup amortises over the query length it doesn't have).
# Measured on the whisper decode step: ~0.8 ms/tok recovered by pinning
# math at the cross-attention shape (kv=1500, q_len=1) — see
# ``docs/reports/decode_step_fusion.md`` §4 and
# ``docs/reports/sdpa_backend_fix.md``.  Eager HF attention and
# torch.compile's Triton online-softmax both beat the default pick here.
#
# The pin is deliberately NARROW — long-context prefill keeps the
# default pick, where mem-efficient genuinely wins (math materialises
# the L×S score matrix, O(L·S) memory):
_SDPA_MATH_Q_LEN_MAX = 8
_SDPA_MATH_KV_LEN_MIN = 256


def _sdpa_math_backend(q: Any, k: Any) -> Any:
    """Backend pin for the ``sdpa`` binding, or ``None`` for default.

    Returns ``SDPBackend.MATH`` only for the measured pathological
    regime — reduced-precision-excluded fp32/fp64, decode-like short
    query length (``q.size(-2) <= _SDPA_MATH_Q_LEN_MAX``) over a long
    key axis (``k.size(-2) >= _SDPA_MATH_KV_LEN_MIN``).  fp16/bf16 keep
    the default pick (flash/efficient are the right choice there), and
    prefill-shaped calls (large ``q_len``) keep it too.
    """
    if q.dtype not in (torch.float32, torch.float64):
        return None
    if q.size(-2) > _SDPA_MATH_Q_LEN_MAX:
        return None
    if k.size(-2) < _SDPA_MATH_KV_LEN_MIN:
        return None
    return SDPBackend.MATH


def _sdpa_torch(q: Any, k: Any, v: Any, *a: Any, **kw: Any) -> Any:
    """``sdpa`` binding: F.sdpa with the decode-shape math-backend pin."""
    kwargs = {"attn_mask": a[0]} if a else {}
    kwargs.update(
        {
            (
                "attn_mask"
                if kk == "arg3"
                else "dropout_p"
                if kk == "arg4"
                else "is_causal"
                if kk == "arg5"
                else "scale"
                if kk == "arg6"
                else "enable_gqa"
                if kk == "arg7"
                else kk
            ): vv
            for kk, vv in kw.items()
            if vv is not None
        }
    )
    backend = _sdpa_math_backend(q, k)
    if backend is None:
        return torch.nn.functional.scaled_dot_product_attention(
            q, k, v, **kwargs
        )
    with sdpa_kernel([backend]):
        return torch.nn.functional.scaled_dot_product_attention(
            q, k, v, **kwargs
        )


def _weight_norm_torch(
    v: Any, g: Any = None, *a: Any, **kw: Any
) -> Any:
    """``aten._weight_norm`` → ``torch._weight_norm``.

    ``dim`` arrives as the canonical ``dim`` attr (schema position 2 —
    see ``_LOCAL_ATTR_SCHEMA_OVERRIDES``), the legacy ``arg2`` spelling
    on hand-minted terms, or a trailing positional; absent entirely at
    the aten default ``dim=0``.  ``g`` is a required Tensor operand —
    the aten schema is ``(Tensor v, Tensor g, int dim=0)`` and
    ``torch._weight_norm`` rejects ``None`` loudly, which is the
    honest failure for a malformed term.
    """
    dim = attr_of(kw, "dim", "arg2", default=None)
    if dim is None and a:
        dim = a[0]
    if dim is None:
        dim = 0
    return torch._weight_norm(v, g, int(_scalar_value(dim)))


