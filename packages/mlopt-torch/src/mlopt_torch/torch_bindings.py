# -- ambient registry snapshot/restore ----------------------------------
# The mint/discovery tests mutate three process-global registries:
# ``_IR_TO_TORCH`` (``prim_mint.register_denotation`` /
# ``seat_shipped`` seat ``synop_*`` bindings onto the ambient dict —
# the load-bearing one, since ``OpTable.full()`` seats its
# ``torch_bindings`` on this same object, so a minted op's fold becomes
# *extractable* where a fresh process would price it ``+inf``),
# ``mlopt_core.ir._OP_REGISTRY`` (``op_def`` at mint time) and
# ``mlopt_core.typing._SHAPE_RULES`` (``register_shape_rule``).
# ``mlopt_core.opmeta`` needs no snapshot — its declaration seam
# already ships ``register_op_meta`` / ``reset_declared``.
#
# The snapshot API lives here (the torch side owns the ambient
# bindings dict) and reaches the two substrate registries through
# ``mlopt_core`` — no eqsat change required.  ``dict(_IR_TO_TORCH)``
# copies only the *materialized* keys: carrier bindings still resolve
# lazily through ``__missing__`` after a restore, exactly as before.


class AmbientRegistrySnapshot(NamedTuple):
    """Frozen copy of the three ambient process-global registries."""

    torch_bindings: dict[str, Any]
    op_registry: dict[str, Any]
    shape_rules: dict[str, Any]


def ambient_registry_snapshot() -> AmbientRegistrySnapshot:
    """Snapshot ``_IR_TO_TORCH`` + ``_OP_REGISTRY`` + ``_SHAPE_RULES``.

    Take the baseline *at test-module import* (collection precedes
    every test body, so it still sees fresh-process state) and
    :func:`restore_ambient_registry` it around each test — or use
    :func:`ambient_registry_scope` for a ``with`` block.
    """
    from mlopt_core.ir import _OP_REGISTRY
    from mlopt_core.typing import _SHAPE_RULES

    return AmbientRegistrySnapshot(
        torch_bindings=dict(_IR_TO_TORCH),
        op_registry=dict(_OP_REGISTRY),
        shape_rules=dict(_SHAPE_RULES),
    )


def restore_ambient_registry(snap: AmbientRegistrySnapshot) -> None:
    """Restore the registries to *snap* — additions AND removals.

    ``clear`` + ``update`` (not ``|=``) so names minted after the
    snapshot are dropped and pre-snapshot overrides are reinstated.
    """
    from mlopt_core.ir import _OP_REGISTRY
    from mlopt_core.typing import _SHAPE_RULES

    _IR_TO_TORCH.clear()
    _IR_TO_TORCH.update(snap.torch_bindings)
    _OP_REGISTRY.clear()
    _OP_REGISTRY.update(snap.op_registry)
    _SHAPE_RULES.clear()
    _SHAPE_RULES.update(snap.shape_rules)


@contextmanager
def ambient_registry_scope() -> Iterator[AmbientRegistrySnapshot]:
    """Snapshot the ambient registries for the ``with`` block's body.

    Restores on exit — including on exception — so a minting probe
    inside the block cannot leak ``synop_*`` ops/bindings/shape rules
    into later tests.  Yields the snapshot for inspection.
    """
    snap = ambient_registry_snapshot()
    try:
        yield snap
    finally:
        restore_ambient_registry(snap)


